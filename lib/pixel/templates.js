export const TEMPLATE_NAMES = Object.freeze(Object.keys(TEMPLATES));

/**
 * Validate every template at module load. A typo in a row would otherwise
 * produce a confusing ragged-grid error only when the user asks for that
 * specific sprite.
 */
for (const [name, template] of Object.entries(TEMPLATES)) {
  if (template.grid.length !== 16) throw new Error(`template ${name} must have 16 rows`);
  for (let index = 0; index < template.grid.length; index += 1) {
    if (template.grid[index].length !== 16) {
      throw new Error(`template ${name} row ${index + 1} has ${template.grid[index].length} columns, expected 16`);
    }
  }
  for (const row of template.grid) {
    for (const symbol of row) {
      if (symbol === '.') continue;
      if (!(symbol in template.theme)) throw new Error(`template ${name} uses role ${symbol} without a theme colour`);
    }
  }
}
