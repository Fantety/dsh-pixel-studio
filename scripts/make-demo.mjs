import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { buildAnimation, buildStatic } from '../lib/pixel/art.js';
import { encodePng } from '../lib/pixel/png.js';
import { checkerPreview, scaleRaster, toRgba } from '../lib/pixel/raster.js';
import { makeSpriteSheet } from '../lib/pixel/sheet.js';
import { TEMPLATE_NAMES } from '../lib/pixel/templates.js';
import { writeArtifacts } from '../lib/pixel/output.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const examples = path.join(root, 'examples');
fs.mkdirSync(examples, { recursive: true });

// A contact sheet of every built-in template, 4 columns.
const frames = TEMPLATE_NAMES.map((name) => {
  const art = buildStatic({ name, template: name });
  return {
    raster: art.frames[0].raster,
    durationMs: 100,
    label: name,
  };
});
const sheet = makeSpriteSheet(frames, { columns: 4, padding: 8, gutter: 8 });
const gallery = scaleRaster(
  checkerPreview(sheet.raster, 8),
  sheet.raster.width * 4,
  sheet.raster.height * 4,
);
fs.writeFileSync(path.join(examples, 'template-gallery.png'), encodePng(gallery.width, gallery.height, toRgba(gallery)));

// One animated sprite with a full delivery: GIF, sheet, viewer, OYPX.
const slime = buildAnimation({
  name: 'slime-idle',
  template: 'slime',
  palette: 'sweetie16',
  effects: { outline: true },
  motion: { preset: 'bob', frames: 8, amplitude: 3 },
  fps: 10,
  loop: 0,
  scale: 10,
  sheetColumns: 8,
});
const slimeOut = writeArtifacts(slime, {
  cwd: examples,
  outputDir: 'slime-idle',
  includeViewer: true,
  includeOypx: true,
});

// A transparent sprite drawn by hand, to show legend + effects.
const heart = buildStatic({
  name: 'tiny-heart',
  legend: {
    O: '#3B0D1A', R: '#EF4B6B', L: '#FF9FB2', W: '#FFE6EA',
  },
  grid: [
    '.OO..OO.',
    'ORROORRO',
    'ORLRRRRO',
    'ORRRRRRO',
    '.ORRRRO.',
    '..ORRO..',
    '...OO...',
    '........',
  ],
  effects: { outline: true, shadow: true, shadowColor: '#00000055', shadowX: 1, shadowY: 1 },
  scale: 16,
});
const heartOut = writeArtifacts(heart, {
  cwd: examples,
  outputDir: 'tiny-heart',
  includeViewer: true,
  includeOypx: true,
});

// The native-canvas example intentionally has no HTML viewer.
const ghost = buildAnimation({
  name: 'native-ghost',
  template: 'ghost',
  palette: 'sweetie16',
  effects: { shadow: true, shadowColor: '#00000055', shadowX: 1, shadowY: 1 },
  motion: { preset: 'float', frames: 8, amplitude: 1 },
  fps: 12,
  loop: 0,
  scale: 10,
});
const ghostOut = writeArtifacts(ghost, {
  cwd: examples,
  outputDir: 'native-ghost',
  includeViewer: false,
  includeOypx: true,
});

const readme = `# Examples

- [\`template-gallery.png\`](template-gallery.png) — all twelve built-in templates.
- [\`slime-idle/\`](slime-idle/) — animated slime with GIF, spritesheet, viewer and OYPX.
- [\`native-ghost/\`](native-ghost/) — native-canvas animation with no standalone viewer.
- [\`tiny-heart/\`](tiny-heart/) — hand-drawn grid with legend, outline and shadow.
- [\`shader-horizon/\`](shader-horizon/) — procedural shader landscape generated by \`make-shader-demo.mjs\`.
- [\`shader-orb/\`](shader-orb/) — procedural shader animation driven by \`phase\`, with GIF + sheet + OYPX.
- [\`showcase/\`](showcase/) — wizard and moonlit grove scenes generated by the showcase script.

Generated by \`scripts/make-demo.mjs\`, \`scripts/make-shader-demo.mjs\`, and \`scripts/make-showcase.mjs\`.
\`slime-idle/slime-idle-viewer.html\` is an optional standalone viewer.
`;
fs.writeFileSync(path.join(examples, 'README.md'), readme);

console.log('wrote', path.join(examples, 'template-gallery.png'));
console.log('wrote', slimeOut.directory);
console.log('wrote', heartOut.directory);
console.log('wrote', ghostOut.directory);
